// App shell for the "your pick" comps (D-070): document head, 104px rail, top bar, phone bottom bar.
//
// There is no mode switch anywhere. One navigation shows what the person can do (server verdict):
//   everyone             Find · My asks · Inbox
//   verified referrer    Find · My asks · Queue · Inbox   (Impact is a link in the queue's header,
//                        so the rail and the phone bar list the same four places)
//   everyone else        a quiet "Give a referral" text link with its "Work email only" note:
//                        at the bottom of the rail, and beside the avatar on phones. It leads to
//                        work-email verification (D-030); it is never a toggle.
// The nav items are content.json's two lists (shell.nav.seeking, shell.nav.giving), merged by id.
import { C, FONTS_CSS, esc, icon, data } from "./lib.mjs";

const S = C.shell;
const NAV = Object.fromEntries([...S.nav.seeking, ...S.nav.giving].map((n) => [n.id, n]));
const ORDER = { seeker: ["find", "asks", "inbox"], referrer: ["find", "asks", "queue", "inbox"] };

/** The one navigation for a person: a verified referrer also gets the Referral queue. */
export const navFor = (verified) => ORDER[verified ? "referrer" : "seeker"].map((id) => NAV[id]);
/** Impact (verified referrers): reached from the Referral queue, not a fifth destination. */
export const IMPACT = NAV.impact;

export function documentPage({ title, css, bodyClass, body }) {
  return `<!doctype html>
<!-- Your pick (D-070) · Triage Desk's layout with Signal's type, no mode switch. Design comp for owner
     review (D-048). Generated by src/build.mjs from content.json: edit src/*.mjs and rebuild rather than
     editing this file. Reference lock: BRIEF.md section 4 (layout, colour) and section 6 (type scale). -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)} · ${esc(S.brand)}</title>
<link rel="stylesheet" href="${FONTS_CSS}">
<link rel="stylesheet" href="tokens.css">
<link rel="stylesheet" href="shell.css">
<link rel="stylesheet" href="${css}">
</head>
<body class="${bodyClass}">
${body}
</body>
</html>
`;
}

export const avatar = (initials, extra = "") =>
  `<button class="avatar hit ${extra}" aria-label="${esc(S.account.ariaLabel)}">${esc(initials)}</button>`;

const navItems = (verified, active, cls, indent) =>
  navFor(verified)
    .map((n) => `
${indent}<a class="${cls}" href="${esc(n.href)}"${n.id === active ? ' aria-current="page"' : ""}>${icon(n.icon, 20, 1.75)}<span>${esc(n.railLabel)}</span></a>`)
    .join("");

/** "Give a referral" for everyone who is not a verified referrer: a quiet link, never a toggle. */
export function giveLink(extra) {
  const e = S.unverifiedEntry;
  return `<a class="give ${extra}" href="${esc(e.href)}"><span class="give__label">${esc(e.label)}</span><span class="give__hint">${esc(e.hint)}</span></a>`;
}

export function rail({ verified, active, initials }) {
  return `<nav class="rail" aria-label="Primary">
    <a class="rail__brand" href="/">${esc(S.brand)}</a>
    <div class="rail__nav">${navItems(verified, active, "rail__item", "      ")}
    </div>
    <div class="rail__foot">${verified ? "" : `
      ${giveLink("give--rail")}`}
      ${avatar(initials)}
    </div>
  </nav>`;
}

export function bottomBar({ verified, active }) {
  return `<nav class="bottombar" aria-label="Primary">${navItems(verified, active, "bottombar__item", "    ")}
  </nav>`;
}

function creditsPill() {
  const p = S.creditsPill;
  return `<button class="credits hit" aria-label="${esc(p.ariaLabel)}">${icon(p.icon, 16)}<span class="only-desktop">${data(p.label)}</span><span class="only-phone">${data(p.shortLabel)}</span></button>`;
}

/**
 * Desktop: the page name on the left; the credits pill (seeker pages only) and alerts on the right.
 * Phone: the account area on the left (avatar, plus "Give a referral" for anyone not verified),
 * then the compact credits pill and alerts. Referrers are never charged, so the referral queue has no
 * credits pill (content.json shell.creditsPill.visibleIn).
 */
export function topBar({ title, verified, credits, initials }) {
  return `<header class="topbar">
    <div class="topbar__account only-phone">${avatar(initials)}${verified ? "" : giveLink("give--top")}</div>
    <p class="topbar__title only-desktop">${esc(title)}</p>
    <div class="topbar__end">${credits ? `
      ${creditsPill()}` : ""}
      <button class="icon-btn hit" aria-label="${esc(S.alerts.ariaLabel)}">${icon(S.alerts.icon, 20, 1.75)}</button>
    </div>
  </header>`;
}
